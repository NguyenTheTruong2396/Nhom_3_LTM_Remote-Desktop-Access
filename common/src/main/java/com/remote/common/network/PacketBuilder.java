package com.remote.common.network;

import java.io.DataOutputStream;
import java.io.IOException;
import java.nio.charset.StandardCharsets;

/**
 * Utility class to write TLV packets to a {@link DataOutputStream}.
 *
 * TLV format: [1 byte Type][4 byte Length (int)][N byte Value]
 */
public final class PacketBuilder {

    private PacketBuilder() {}

    /**
     * Writes a raw-bytes TLV packet.
     *
     * @param out     the output stream to write to
     * @param type    packet type (see {@link PacketType})
     * @param payload byte array payload; may be {@code null} or empty for 0-length packets
     * @throws IOException if an I/O error occurs
     */
    public static void write(DataOutputStream out, byte type, byte[] payload) throws IOException {
        int length = (payload != null) ? payload.length : 0;
        out.writeByte(type);
        out.writeInt(length);
        if (length > 0) {
            out.write(payload);
        }
        out.flush();
    }

    /**
     * Writes a UTF-8 string payload TLV packet.
     *
     * @param out     the output stream to write to
     * @param type    packet type
     * @param text    string payload encoded as UTF-8
     * @throws IOException if an I/O error occurs
     */
    public static void writeText(DataOutputStream out, byte type, String text) throws IOException {
        byte[] payload = (text != null) ? text.getBytes(StandardCharsets.UTF_8) : new byte[0];
        write(out, type, payload);
    }

    /**
     * Writes a zero-length TLV packet (e.g. PING, PONG, DISCONNECT).
     *
     * @param out  the output stream to write to
     * @param type packet type
     * @throws IOException if an I/O error occurs
     */
    public static void writeEmpty(DataOutputStream out, byte type) throws IOException {
        out.writeByte(type);
        out.writeInt(0);
        out.flush();
    }

    /**
     * Convenience: writes an AUTH_REQ packet with "sessionId|passcode".
     *
     * @param out       output stream
     * @param sessionId session ID generated by server
     * @param passcode  user-entered passcode
     * @throws IOException if an I/O error occurs
     */
    public static void writeAuthRequest(DataOutputStream out, String sessionId, String passcode)
            throws IOException {
        writeText(out, PacketType.AUTH_REQ, sessionId + "|" + passcode);
    }

    /**
     * Convenience: writes an AUTH_RESP packet.
     *
     * @param out     output stream
     * @param success {@code true} → 1 (accepted), {@code false} → 0 (rejected)
     * @throws IOException if an I/O error occurs
     */
    public static void writeAuthResponse(DataOutputStream out, boolean success) throws IOException {
        write(out, PacketType.AUTH_RESP, new byte[]{(byte) (success ? 1 : 0)});
    }

    /**
     * Convenience: writes a FRAME_DATA packet containing a JPEG byte array.
     *
     * @param out       output stream
     * @param jpegBytes raw JPEG bytes
     * @throws IOException if an I/O error occurs
     */
    public static void writeFrameData(DataOutputStream out, byte[] jpegBytes) throws IOException {
        write(out, PacketType.FRAME_DATA, jpegBytes);
    }
}
